//! # tensa-llm
//!
//! Локальный инференс LLM Tensa (ТЗ tensa-llm, ADR-003):
//! двухуровневый FFI к llama.cpp — `tensa-llama-sys` (unsafe, уровень 1)
//! и `tensa-llama` (безопасная обёртка, уровень 2), плюс контроль версий
//! и автообновление с подтверждением (уровень 3).
//!
//! Крейт-фасад: весь публичный API живёт в [`tensa_llama`] и
//! реэкспортируется отсюда.
//!
//! Ограничения ТЗ: не маршрутизирует (это `tensa-router`), не хранит
//! историю, не выполняет действия, не логирует секреты.

pub use tensa_llama::*;

/// Версия крейта.
pub const VERSION: &str = env!("CARGO_PKG_VERSION");
